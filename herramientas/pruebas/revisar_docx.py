"""Revisa que un .docx no tenga errores de estructura que Word no perdona.

LibreOffice abre casi cualquier cosa; Word es más estricto con el orden de los
elementos. Comprueba, en tablas y celdas, que los hijos van en el orden del
esquema y que no hay ninguno repetido, y que las casillas tienen su espacio de
nombres declarado.

También revisa las propiedades que delatan la plantilla de python-docx: autor
«python-docx», fecha de 2013, idioma inglés, miniatura en blanco e imágenes sin
texto alternativo.

Uso: .venv/bin/python herramientas/pruebas/revisar_docx.py documento.docx
Sale con 0 si está bien y con 1 si encuentra problemas.
"""
import sys
import zipfile
from pathlib import Path

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from docx_util import _ORDEN  # noqa: E402

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"


def problemas(ruta):
    with zipfile.ZipFile(ruta) as z:
        raiz = etree.fromstring(z.read("word/document.xml"))
        nucleo = z.read("docProps/core.xml").decode("utf-8")
        estilos = etree.fromstring(z.read("word/styles.xml"))
        relaciones = z.read("_rels/.rels").decode("utf-8")
    encontrados = []
    if ">python-docx<" in nucleo or "generated by python-docx" in nucleo:
        encontrados.append("propiedades: el autor o la descripción dicen «python-docx»")
    if "2013-12-23" in nucleo:
        encontrados.append("propiedades: fecha de la plantilla (2013)")
    lang = estilos.find(f".//{{{W}}}docDefaults//{{{W}}}lang")
    if lang is None or not (lang.get(f"{{{W}}}val") or "").startswith("es"):
        encontrados.append("idioma: el documento no está en español (Word lo marcaría todo como faltas)")
    if "thumbnail" in relaciones:
        encontrados.append("miniatura: lleva la vista previa en blanco de la plantilla")
    WP = "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
    for n, docpr in enumerate(raiz.iter(f"{{{WP}}}docPr")):
        if not (docpr.get("descr") or "").strip():
            encontrados.append(f"imagen nº {n + 1}: sin texto alternativo")
    for padre, orden in _ORDEN.items():
        for n, nodo in enumerate(raiz.iter(f"{{{W}}}{padre}")):
            nombres = [etree.QName(h).localname for h in nodo]
            repetidos = {x for x in nombres if nombres.count(x) > 1}
            if repetidos:
                encontrados.append(f"{padre} nº {n + 1}: repetido {', '.join(sorted(repetidos))}")
            conocidos = [orden.index(x) for x in nombres if x in orden]
            if conocidos != sorted(conocidos):
                encontrados.append(f"{padre} nº {n + 1}: fuera de orden {nombres}")
    if raiz.find(".//{http://schemas.microsoft.com/office/word/2010/wordml}checkbox") is not None:
        if "w14" not in (raiz.get("{http://schemas.openxmlformats.org/markup-compatibility/2006}Ignorable") or ""):
            encontrados.append("hay casillas w14 pero el documento no declara mc:Ignorable=\"w14\"")
    return encontrados


if __name__ == "__main__":
    lista = problemas(sys.argv[1])
    for p in lista[:20]:
        print("✗", p)
    if len(lista) > 20:
        print(f"… y {len(lista) - 20} más")
    print(f"{len(lista)} problemas" if lista else "✓ sin problemas de estructura ni de propiedades")
    sys.exit(1 if lista else 0)
