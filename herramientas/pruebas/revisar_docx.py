"""Revisa que un .docx no tenga errores de estructura que Word no perdona.

LibreOffice abre casi cualquier cosa; Word es más estricto con el orden de los
elementos. Comprueba, en tablas y celdas, que los hijos van en el orden del
esquema y que no hay ninguno repetido, que cada celda termina en un párrafo,
que los controles de contenido no repiten número y que las casillas tienen su
espacio de nombres declarado.

También revisa las propiedades que delatan la plantilla de python-docx: autor
«python-docx», fecha de 2013, idioma inglés, miniatura en blanco e imágenes sin
texto alternativo.

Uso: .venv/bin/python herramientas/pruebas/revisar_docx.py documento.docx [--json]
Sale con 0 si está bien y con 1 si encuentra problemas.
Con --json, cada problema lleva su tipo y su gravedad, para otros scripts
(comprobar.py de Puri): así no dependen de cómo está escrito el mensaje.
  estructura    → bloquea   (Word puede negarse a abrirlo o «repararlo»)
  propiedades   → importante
  accesibilidad → importante
"""
import sys
import zipfile
from pathlib import Path

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from docx_util import _ORDEN  # noqa: E402

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"


def problemas_detallados(ruta):
    """[(tipo, mensaje)] con tipo: estructura, propiedades o accesibilidad."""
    with zipfile.ZipFile(ruta) as z:
        raiz = etree.fromstring(z.read("word/document.xml"))
        nucleo = z.read("docProps/core.xml").decode("utf-8")
        estilos = etree.fromstring(z.read("word/styles.xml"))
        relaciones = z.read("_rels/.rels").decode("utf-8")
    encontrados = []
    if ">python-docx<" in nucleo or "generated by python-docx" in nucleo:
        encontrados.append(("propiedades", "propiedades: el autor o la descripción dicen «python-docx»"))
    if "2013-12-23" in nucleo:
        encontrados.append(("propiedades", "propiedades: fecha de la plantilla (2013)"))
    lang = estilos.find(f".//{{{W}}}docDefaults//{{{W}}}lang")
    if lang is None or not (lang.get(f"{{{W}}}val") or "").startswith("es"):
        encontrados.append(("propiedades", "idioma: el documento no está en español (Word lo marcaría todo como faltas)"))
    if "thumbnail" in relaciones:
        encontrados.append(("propiedades", "miniatura: lleva la vista previa en blanco de la plantilla"))
    WP = "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
    for n, docpr in enumerate(raiz.iter(f"{{{WP}}}docPr")):
        if not (docpr.get("descr") or "").strip():
            encontrados.append(("accesibilidad", f"imagen nº {n + 1}: sin texto alternativo"))
    for padre, orden in _ORDEN.items():
        for n, nodo in enumerate(raiz.iter(f"{{{W}}}{padre}")):
            nombres = [etree.QName(h).localname for h in nodo]
            repetidos = {x for x in nombres if nombres.count(x) > 1}
            if repetidos:
                encontrados.append(("estructura", f"{padre} nº {n + 1}: repetido {', '.join(sorted(repetidos))}"))
            conocidos = [orden.index(x) for x in nombres if x in orden]
            if conocidos != sorted(conocidos):
                encontrados.append(("estructura", f"{padre} nº {n + 1}: fuera de orden {nombres}"))
    for n, celda in enumerate(raiz.iter(f"{{{W}}}tc")):
        bloques = [h for h in celda if etree.QName(h).localname != "tcPr"]
        if not bloques or etree.QName(bloques[-1]).localname != "p":
            encontrados.append(("estructura", f"celda nº {n + 1}: no termina en un párrafo (Word puede darlo por dañado)"))
    numeros = [i.get(f"{{{W}}}val") for i in raiz.iter(f"{{{W}}}id") if etree.QName(i.getparent()).localname == "sdtPr"]
    repetidos = sorted({x for x in numeros if numeros.count(x) > 1})
    if repetidos:
        encontrados.append(("estructura", f"controles con el mismo w:id: {', '.join(repetidos[:5])}"))
    if raiz.find(".//{http://schemas.microsoft.com/office/word/2010/wordml}checkbox") is not None:
        if "w14" not in (raiz.get("{http://schemas.openxmlformats.org/markup-compatibility/2006}Ignorable") or ""):
            encontrados.append(("estructura", "hay casillas w14 pero el documento no declara mc:Ignorable=\"w14\""))
    return encontrados


GRAVEDAD = {"estructura": "bloquea", "propiedades": "importante", "accesibilidad": "importante"}


def problemas(ruta):
    return [mensaje for _, mensaje in problemas_detallados(ruta)]


if __name__ == "__main__":
    if "--json" in sys.argv:
        import json
        detalle = problemas_detallados(next(a for a in sys.argv[1:] if a != "--json"))
        print(json.dumps([{"tipo": t, "gravedad": GRAVEDAD[t], "mensaje": m} for t, m in detalle], ensure_ascii=False, indent=2))
        sys.exit(1 if detalle else 0)
    lista = problemas(sys.argv[1])
    for p in lista[:20]:
        print("✗", p)
    if len(lista) > 20:
        print(f"… y {len(lista) - 20} más")
    print(f"{len(lista)} problemas" if lista else "✓ sin problemas de estructura ni de propiedades")
    sys.exit(1 if lista else 0)
