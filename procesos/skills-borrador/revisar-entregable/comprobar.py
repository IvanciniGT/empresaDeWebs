"""Comprobaciones mecánicas de un envío antes de la revisión a mano de Puri.

No da el veredicto: señala lo que hay que mirar. Lo que no salga aquí no
está aprobado; solo significa que la máquina no sabe verlo.

Uso (Python del sistema, sin dependencias; usa pdftotext, pdfinfo y pdffonts):
    python3 comprobar.py <carpeta entregables> <expediente.md> [más fuentes .md/.json]
"""
import re
import subprocess
import sys
import zipfile
from pathlib import Path

# Palabras que suelen delatar una afirmación sin fuente o una promesa.
ALARMAS = [
    r"\btodos?\b", r"\btodas?\b", r"\bnunca\b", r"\bsiempre\b", r"\bning[uú]n[oa]?\b",
    r"\bnadie\b", r"\bgaranti", r"\bprometemos\b", r"\bse queda con\b", r"\blo que más\b",
    r"\bsuele\b", r"\bseguro\b", r"\bseguramente\b", r"\bmuchos?\b", r"\bpocas?\b",
    r"\bm[aá]s (?:llamadas|clientes|visitas)\b", r"\bfiable\b", r"\bcomprobado\b",
    r"\bllamamos\b", r"\bos llamamos\b", r"\bno ten[eé]is\b", r"\bno existe\b",
]
HUECO = re.compile(r"\[(?!x\]|\s\])[^\]\n]{2,60}\](?!\()")
CIFRA = re.compile(r"(?<![\w/§.])(\d{1,3}(?:[.,]\d{1,3})?)\s*(%|€|km|m\b|metros|años|minutos|opiniones|reseñas)?")


def texto_pdf(ruta: Path) -> str:
    return subprocess.run(["pdftotext", "-layout", str(ruta), "-"], capture_output=True, text=True).stdout


def texto_docx(ruta: Path) -> str:
    with zipfile.ZipFile(ruta) as z:
        xml = z.read("word/document.xml").decode("utf8")
        pies = [z.read(n).decode("utf8") for n in z.namelist() if re.match(r"word/footer\d*\.xml", n)]
    partes = []
    for x in [xml, *pies]:
        x = re.sub(r"</w:p>", "\n", x)
        partes.append(re.sub(r"<[^>]+>", "", x))
    return "\n".join(partes)


def frases(texto: str):
    plano = re.sub(r"\s+", " ", texto)
    return [f.strip() for f in re.split(r"(?<=[.!?»])\s+", plano) if f.strip()]


def revisar_docx(ruta: Path, avisos: list):
    with zipfile.ZipFile(ruta) as z:
        nombres = z.namelist()
        estilos = z.read("word/styles.xml").decode("utf8")
        doc = z.read("word/document.xml").decode("utf8")
        core = z.read("docProps/core.xml").decode("utf8") if "docProps/core.xml" in nombres else ""
    idiomas = set(re.findall(r'<w:lang w:val="([^"]+)"', estilos + doc))
    if not idiomas or any(not i.startswith("es") for i in idiomas):
        avisos.append(("importante", ruta.name, f"Idioma del documento: {sorted(idiomas) or 'sin definir'}; debe ser es-ES"))
    autor = re.search(r"<dc:creator>([^<]*)<", core)
    if autor and re.search(r"python-docx|^$", autor.group(1)):
        avisos.append(("importante", ruta.name, f"Autor en propiedades: «{autor.group(1)}»"))
    if "generated by python-docx" in core:
        avisos.append(("importante", ruta.name, "Descripción en propiedades: «generated by python-docx»"))
    creado = re.search(r"<dcterms:created[^>]*>([^<]*)<", core)
    if creado and creado.group(1)[:4] < "2020":
        avisos.append(("importante", ruta.name, f"Fecha de creación en propiedades: {creado.group(1)}"))
    if re.search(r"<dc:title\s*/>|<dc:title></dc:title>", core):
        avisos.append(("menor", ruta.name, "Sin título en propiedades"))
    if "docProps/thumbnail.jpeg" in nombres:
        avisos.append(("menor", ruta.name, "Lleva miniatura interna: comprobar que no es una página en blanco"))
    sin_alt = [d for d in re.findall(r"<wp:docPr [^>]*>", doc) if "descr=" not in d]
    if sin_alt:
        avisos.append(("menor", ruta.name, f"{len(sin_alt)} imagen(es) sin texto alternativo"))
    casillas = doc.count("<w14:checkbox>")
    avisos.append(("info", ruta.name, f"{casillas} casillas clicables (w14:checkbox): probarlas en Microsoft Word"))


def revisar_pdf(ruta: Path, avisos: list):
    info = subprocess.run(["pdfinfo", str(ruta)], capture_output=True, text=True).stdout
    paginas = re.search(r"Pages:\s+(\d+)", info)
    avisos.append(("info", ruta.name, f"{paginas.group(1) if paginas else '?'} páginas"))
    if "Tagged:          yes" not in info:
        avisos.append(("menor", ruta.name, "PDF sin etiquetar (accesibilidad)"))
    fuentes = subprocess.run(["pdffonts", str(ruta)], capture_output=True, text=True).stdout
    familias = sorted({re.sub(r"^[A-Z]{6}\+", "", l.split()[0]).split("-")[0] for l in fuentes.splitlines()[2:] if l.strip()})
    avisos.append(("info", ruta.name, f"Tipografías incrustadas: {', '.join(familias)}: comprobar licencia"))


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    carpeta, expediente = Path(sys.argv[1]), Path(sys.argv[2])
    fuentes = expediente.read_text(encoding="utf8")
    for extra in sys.argv[3:]:
        fuentes += Path(extra).read_text(encoding="utf8", errors="ignore")
    avisos, textos = [], {}

    for f in sorted(carpeta.iterdir()):
        if f.name.startswith("~$"):
            avisos.append(("menor", f.name, "Fichero de bloqueo de Word: alguien tiene el documento abierto. No adjuntar"))
            continue
        if f.name.startswith(".") or f.is_dir():
            continue
        if re.search(r"interno|previo|gu[ií]a de estilos", f.name, re.I):
            avisos.append(("bloquea", f.name, "Parece un documento interno dentro de entregables/"))
        if f.suffix == ".pdf":
            textos[f.name] = texto_pdf(f)
            revisar_pdf(f, avisos)
        elif f.suffix == ".docx":
            textos[f.name] = texto_docx(f)
            revisar_docx(f, avisos)
        elif f.suffix in (".md", ".txt"):
            textos[f.name] = f.read_text(encoding="utf8")

    print(f"# Comprobación automática · {carpeta}\n")
    print("## Avisos\n")
    for gravedad, donde, que in avisos:
        print(f"- [{gravedad}] {donde} · {que}")

    for nombre, texto in textos.items():
        print(f"\n## {nombre}\n")
        huecos = sorted(set(HUECO.findall(texto)))
        if huecos:
            print("**Huecos sin rellenar** (bloquean salvo que sean intencionados):")
            for h in huecos:
                print(f"- {h}")
        print("\n**Cifras que no aparecen tal cual en las fuentes** (rastrear una a una):")
        vistas = set()
        for f in frases(texto):
            for num, unidad in CIFRA.findall(f):
                clave = (num, unidad)
                if clave in vistas or num in fuentes:
                    continue
                vistas.add(clave)
                print(f"- {num}{(' ' + unidad) if unidad else ''} · «{f[:140]}»")
        print("\n**Frases con palabras de alarma** (¿tienen fuente?, ¿prometen algo?):")
        for f in frases(texto):
            if any(re.search(p, f, re.I) for p in ALARMAS):
                print(f"- «{f[:160]}»")

    print("\n## Lo que esta comprobación NO mira\n")
    print("Ortografía, tono, verdad de cada frase, maquetación, el Word en Microsoft Word, "
          "el móvil y la coherencia de una cifra entre documentos. Eso es la revisión a mano.")


if __name__ == "__main__":
    main()
